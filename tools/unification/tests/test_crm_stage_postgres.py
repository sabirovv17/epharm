"""Opt-in, disposable PG18 -> PG16 engine test. Never uses restored source databases."""

import copy
import json
import os
from pathlib import Path
import subprocess
import tempfile
import time
import unittest

from test_crm_stage import stage, SYNTHETIC_SECRET


@unittest.skipUnless(os.environ.get("RUN_CRM_STAGE_PG_TESTS") == "1", "opt-in disposable PostgreSQL test")
class CrmStagePostgresTest(unittest.TestCase):
    def test_typed_copy_replay_and_failed_fk_are_transactional(self):
        # Images must already exist; this test never pulls or prunes images.
        for image in ("postgres:18-alpine", "postgres:16-alpine"):
            result = subprocess.run(["docker", "image", "inspect", image], capture_output=True)
            self.assertEqual(0, result.returncode, "required local test image is absent")
        capacity = stage.Database("epharm-unify-pg-20261029", "epharm", "epharm_unified_candidate").inspect()
        self.assertGreater(capacity["freeBytes"], stage.MIN_HEADROOM + 256 * 1024 ** 2)
        suffix = str(time.time_ns())
        names = ["epharm-stage-test-src-" + suffix, "epharm-stage-test-dst-" + suffix]
        created = []
        with tempfile.TemporaryDirectory(prefix="crm-stage-engine-") as directory:
            root = Path(directory)
            try:
                for name, image, database in zip(names, ("postgres:18-alpine", "postgres:16-alpine"),
                                                  ("synthetic_source", "epharm_synthetic_candidate")):
                    result = subprocess.run(["docker", "run", "--detach", "--rm", "--network", "none", "--name", name,
                                             "-e", "POSTGRES_USER=synthetic", "-e", "POSTGRES_PASSWORD=synthetic-test-only",
                                             "-e", "POSTGRES_DB=" + database, image], capture_output=True)
                    self.assertEqual(0, result.returncode, "cannot create isolated synthetic database")
                    created.append(name)
                for name in names:
                    for _ in range(100):
                        ready = subprocess.run(["docker", "exec", name, "pg_isready", "-h", "127.0.0.1", "-U", "synthetic"], capture_output=True)
                        if ready.returncode == 0:
                            break
                        time.sleep(0.2)
                    else:
                        self.fail("synthetic database did not become ready")
                source = stage.Database(names[0], "synthetic", "synthetic_source")
                target = stage.Database(names[1], "synthetic", "epharm_synthetic_candidate")
                ddl = """
CREATE TYPE public.user_role AS ENUM ('admin','staff');
CREATE TABLE public.accounts (
 id uuid PRIMARY KEY,password_hash text,fixed char(4),amount numeric(14,3),role public.user_role,
 dates date[],ids uuid[],ip inet,details jsonb,event_time timestamptz(3),
 request_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,escaped text,
 CONSTRAINT positive_amount CHECK(amount>=0));
CREATE TABLE public.nodes (id text PRIMARY KEY,account_id uuid,parent_id text);
INSERT INTO public.accounts(id,password_hash,fixed,amount,role,dates,ids,ip,details,event_time,request_number,escaped)
VALUES ('11111111-2222-4333-8444-555555555555',SECRET,'x',1234567.120,'admin',
 ARRAY['2026-10-01'::date,NULL],ARRAY['11111111-2222-4333-8444-555555555555'::uuid],
 '192.0.2.1/24','{"file":"storage/test/path.txt","n":1.20}',
 '2026-10-29 01:02:03.123+00',7,ESCAPED);
INSERT INTO public.nodes VALUES ('A','11111111-2222-4333-8444-555555555555','B'),('B',NULL,'A');
ALTER TABLE public.nodes ADD CONSTRAINT nodes_account_fkey FOREIGN KEY(account_id) REFERENCES public.accounts(id) ON DELETE SET NULL;
ALTER TABLE public.nodes ADD CONSTRAINT nodes_parent_fkey FOREIGN KEY(parent_id) REFERENCES public.nodes(id) ON DELETE RESTRICT;
CREATE FUNCTION public.forbidden_source_trigger() RETURNS trigger LANGUAGE plpgsql AS $source$
 BEGIN RAISE EXCEPTION 'DO_NOT_REPLAY $stage_verify$'; END $source$;
CREATE TRIGGER forbidden_source_trigger BEFORE INSERT OR UPDATE ON public.accounts FOR EACH ROW EXECUTE FUNCTION public.forbidden_source_trigger();
""".replace("SECRET", stage.literal(SYNTHETIC_SECRET)).replace("ESCAPED", stage.literal("\\N\n\\.\tӘ\r\v\f\b\x01"))
                source.run(ddl)
                backup = root / "synthetic-source.sql"
                backup.write_text(ddl)
                backup.chmod(0o600)
                metadata = stage.parse_json(source.readonly(stage.metadata_sql()))
                stage.validate_metadata(metadata, 2)
                artifact_path = root / "snapshot.json"
                exported = stage.export_artifact(source, stage.schema_hash(metadata), backup, stage.file_hash(backup), artifact_path, 2)
                artifact = stage.parse_json(artifact_path.read_bytes())
                self.assertEqual(3, exported["rowCount"])
                account = artifact["tables"]["accounts"][0]
                self.assertIn("x   ", account)
                self.assertIn(SYNTHETIC_SECRET, account)
                self.assertEqual(0o600, artifact_path.stat().st_mode & 0o777)
                info = target.inspect()
                report_path = root / "load.json"
                loaded = stage.load_artifact(target, artifact_path, exported["artifactSha256"], info["identitySha256"], 2,
                                             stage.MIN_HEADROOM, report_path)
                self.assertEqual("imported_and_verified", loaded["mode"])
                replay = stage.load_artifact(target, artifact_path, exported["artifactSha256"], info["identitySha256"], 2,
                                             stage.MIN_HEADROOM, report_path)
                self.assertEqual("verified_existing_noop", replay["mode"])
                self.assertEqual(2, loaded["foreignKeys"])
                self.assertEqual(1, loaded["inertSequenceStates"])
                self.assertEqual(1, loaded["inertTriggers"])
                self.assertNotIn(SYNTHETIC_SECRET, report_path.read_text())
                schema = "crm_stage_" + exported["artifactSha256"][:16]
                target_rows = [stage.parse_json(line) for line in target.readonly(stage.data_query(metadata, schema)).splitlines()]
                self.assertEqual({json.dumps(row, sort_keys=True) for row in artifact["tables"]["accounts"]},
                                 {json.dumps(row["values"], sort_keys=True) for row in target_rows if row["table"] == "accounts"})
                bad = copy.deepcopy(artifact)
                bad["tables"]["nodes"][0][1] = '99999999-2222-4333-8444-555555555555'
                bad["checksums"] = [stage.table_checksum(t, bad["tables"][t["name"]]) for t in bad["metadata"]["tables"]]
                bad_path = root / "bad-snapshot.json"
                stage.private_write(bad_path, stage.encoded(bad))
                bad_sha = stage.file_hash(bad_path)
                with self.assertRaises(stage.StageError):
                    stage.load_artifact(target, bad_path, bad_sha, info["identitySha256"], 2, stage.MIN_HEADROOM, root / "bad-load.json")
                self.assertEqual("f", target.readonly("SELECT to_regnamespace(" + stage.literal("crm_stage_" + bad_sha[:16]) + ") IS NOT NULL;").strip())
                target.run("UPDATE " + stage.qi(schema) + ".accounts SET password_hash='changed-synthetic';")
                with self.assertRaises(stage.StageError):
                    stage.load_artifact(target, artifact_path, exported["artifactSha256"], info["identitySha256"], 2,
                                        stage.MIN_HEADROOM, report_path)
            finally:
                for name in created:
                    subprocess.run(["docker", "rm", "--force", "--volumes", name], capture_output=True)


if __name__ == "__main__":
    unittest.main()
