/// Один пункт FAQ. Может содержать:
/// • `intro` — текст до буллетов
/// • `bullets` — список буллет-пунктов
/// • `text` — единый текст (если нет буллетов)
/// • `outro` — текст после буллетов
///
/// Внутри строк допустимы маркеры:
///   • `[link]...[/link]` — рендерится как акцентный teal текст (без подчёркивания)
///   • `**...**` — жирный фрагмент
