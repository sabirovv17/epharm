import 'package:flutter/painting.dart';
import 'package:flutter_cache_manager/flutter_cache_manager.dart';

/// Общий ДИСКОВЫЙ кэш фото витрины (через прокси /api/media/img).
///
/// Зачем: голый `Image.network` держит декодированный кадр только в памяти
/// (`PaintingBinding.imageCache`). При скролле ленты плитки рециклируются, а под
/// лимитом памяти кадры выбиваются — и при возврате плитки во вьюпорт идёт
/// ПОВТОРНЫЙ сетевой запрос на прокси + повторный декод → микро-лаг скролла.
/// После рестарта приложения кэша нет вовсе. Дисковый кэш убирает оба сценария:
/// фото грузится по сети один раз, дальше берётся с диска (быстро, без round-trip
/// на backend — это ещё и разгружает прокси под нагрузкой многих пользователей).
///
/// Один инстанс на всё приложение — плитки ленты/каталога/каруселей делят один
/// LRU и не плодят дубли файлов.
class MediaCache {
  MediaCache._();

  static final CacheManager instance = CacheManager(
    Config(
      'epharm_media', // отдельный bucket, не мешаем дефолтному кэшу
      stalePeriod: const Duration(days: 14),
      maxNrOfCacheObjects: 600, // фото витрины немного — держим разумно
    ),
  );
}

/// Лёгкий тюнинг in-memory `imageCache`. Дисковый кэш — основной фикс, но чуть
/// больший потолок байт уменьшает частоту повторного ДЕКОДА уже виденных фото
/// при скролле длинной ленты. Держим консервативно (низкий риск на слабых
/// устройствах): диск всё равно страхует, поэтому без агрессивных значений.
void tuneImageCache() {
  PaintingBinding.instance.imageCache.maximumSizeBytes = 120 << 20; // 120 МБ (дефолт 100)
}
