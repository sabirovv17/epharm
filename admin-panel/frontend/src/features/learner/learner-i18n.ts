function interpolate(value: string, vars?: Vars) {
  if (!vars) return value
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`))
}

export function learnerTranslate(lang: Lang, source: string, vars?: Vars) {
  return interpolate(lang === 'kk' ? (kk[source] ?? source) : source, vars)
}

export function currentLearnerTranslate(source: string, vars?: Vars) {
  return learnerTranslate(useUiStore.getState().language, source, vars)
}

export function useLearnerT() {
  const language = useUiStore((state) => state.language)
  return (source: string, vars?: Vars) => learnerTranslate(language, source, vars)
}
